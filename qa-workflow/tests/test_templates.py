def test_every_template_has_required_sections():
    for rel, keys in REQUIRED_SECTIONS.items():
        path = KBASE / rel
        assert path.is_file(), f"模板缺失: {rel}"
        text = path.read_text(encoding="utf-8")
        for kw in keys:
            assert kw in text, f"{rel} 缺少字段: {kw}"
